export async function seedLocalities() {
  const ops = PRAYAGRAJ_LOCALITIES.map((loc) => ({
    updateOne: {
      filter: { city: 'Prayagraj', localityName: loc.name },
      update: {
        $setOnInsert: {
          city: 'Prayagraj',
          localityName: loc.name,
          slug: slugifyText(`${loc.name}-prayagraj`),
          location: { type: 'Point', coordinates: loc.coords },
          isPopular: loc.isPopular,
          active: true,
        },
      },
      upsert: true,
    },
  }));
  await Locality.bulkWrite(ops);
}

export async function seedAdminUser({
  name = process.env.ADMIN_NAME || 'RoomKhoj Admin',
  mobile = process.env.ADMIN_MOBILE || '9999999999',
  password = process.env.ADMIN_PASSWORD || 'Admin@1234',
} = {}) {
  const existing = await User.findOne({ mobile });
  if (existing) return existing;

  const passwordHash = await bcrypt.hash(password, 12);
  return User.create({
    name,
    mobile,
    passwordHash,
    role: 'admin',
    phoneVerified: true,
    accountStatus: 'active',
    isDirectOwnerDeclared: false,
  });
}

